#!/usr/bin/env python3
"""Generate apps/airlisp/src/lucide.rs (codepoints of the Lucide icons the UI uses) from assets/icons/info.json."""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
NAMES = """folder folder-open file file-code play square rotate-cw search triangle-alert circle-x circle-alert check chevron-right
chevron-down chevron-up x plus settings list-tree terminal trash-2 folder-tree git-branch circle ban info arrow-up arrow-down
git-commit-horizontal refresh-cw history diff menu ellipsis square-terminal download palette keyboard sliders-horizontal code-xml
folder-plus file-plus pencil copy save sun moon git-fork external-link zap circle-check list layers package cloud-download
git-pull-request hammer bug sparkles panel-left file-text braces scroll-text eraser circle-stop link globe hard-drive
minus maximize minimize""".split()

info = json.loads((ROOT / "assets" / "icons" / "info.json").read_text(encoding="utf-8"))
lines = ["//! Generated by tools/gen_lucide.py from Lucide (ISC license, see assets/icons/LICENSE). Do not edit.", ""]
for n in NAMES:
    if n not in info:
        raise SystemExit(f"unknown Lucide icon: {n}")
    code = int(info[n]["encodedCode"].lstrip("\\"), 16)
    lines.append("pub const %s: char = '\\u{%x}';" % (n.upper().replace("-", "_"), code))
(ROOT / "apps" / "airlisp" / "src" / "lucide.rs").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {len(NAMES)} icons")
